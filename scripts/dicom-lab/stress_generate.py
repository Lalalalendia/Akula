#!/usr/bin/env python3
"""Generate one 100 MiB, 200-frame, signed 16-bit multi-frame test DICOM."""
import json
import pathlib
import struct
import generate

root = pathlib.Path(__file__).resolve().parent
width = height = 512
frames = 200
one = b"".join(struct.pack("<h", (i * 13) % 60001 - 30000) for i in range(width * height))
raw = one * frames
assert len(raw) == 104_857_600, len(raw)
generate.FIXTURES.mkdir(exist_ok=True)
generate.create("stress_200x512x512_i16.dcm", width, height, 16, 1, raw,
                "1.2.840.10008.1.2.1", signed=True,
                frames=frames, sop=generate.MF_UID)
row = generate.manifest[-1]
assert row["frames"] == frames and row["size"] > 100_000_000
(root / "stress_manifest.json").write_text(json.dumps(row, indent=2))
print("STRESS_GENERATED bytes", len(raw), "frames", frames, "pixel_sha256", row["pixel_sha256"])

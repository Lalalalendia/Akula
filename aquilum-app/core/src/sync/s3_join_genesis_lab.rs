//! YC-S3-T01d E3a — OFFLINE join-genesis proof, not an S3 client.
//!
//! Recipient MUST learn owner public keys, scope, root/policy BLAKE3 pins,
//! and fresh challenge from an independently authenticated pairing channel.
//! A server-supplied signing key/pin is never authorization (no silent TOFU).
//! This module does not create invitations, custody keys, read S3, use WinCred,
//! mutate guarded app-data, enroll trust, operate File Gate or enable Sync.
//! Generation >1 requires a separate pinned ancestry procedure (not E3a).

use std::collections::BTreeSet;

use ring::signature::{UnparsedPublicKey, ED25519};
use serde::{Deserialize, Serialize};

use super::{
    DecodedDsseEnvelope, PublisherPolicyV1, S3Keyspace, S3PackedHeadV2, VaultId,
};
use super::s3_publisher_policy_lab::{valid_for_scope, MAX_OWNER_KEYS};
use super::s3_signed_root_paev1::{pae, YANDEX_ENDPOINT, YANDEX_REGION};

pub const JOIN_GENESIS_TYPE: &str =
    "application/vnd.akula.vault-join-genesis+json;version=1";
pub const MAX_JOIN_PAYLOAD_BYTES: usize = 4096;
pub const MAX_JOIN_SIGNATURES: usize = 4;

/// These expectations must be carried out-of-band and verified by the
/// joining user/device independently of anything returned by Yandex S3.
/// The 32-byte challenge is generated by a cryptographic RNG OUTSIDE E3a.
pub struct IndependentlyApprovedJoin<'a> {
    pub bucket: &'a str,
    pub keyspace: &'a S3Keyspace,
    pub pinned_genesis_root_blake3: &'a str,
    pub pinned_genesis_policy_blake3: &'a str,
    pub trusted_owner_keys: &'a [[u8; 32]],
    pub owner_quorum: usize,
    /// Exactly 64 lower-case hex digits; zero challenge is forbidden.
    pub recipient_challenge_hex: &'a str,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum JoinGenesisError {
    InvalidExternalApproval,
    InvalidPolicy,
    NotGenesis,
    WrongIndependentPin,
    WrongOwnerAuthority,
    InvalidEnvelope,
    InvalidType,
    MissingOwnerQuorum,
    InvalidSignedPayload,
    WrongScope,
    WrongRootOrPolicy,
    WrongChallenge,
}

/// Read-only evidence, *not* a writer grant or an automatic policy enrolment.
/// The host must separately perform a fully pinned V2 S3 read, user confirmation
/// and guarded trust-anchor commit before reporting that a vault is trusted.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct JoinGenesisReview {
    pub root_blake3: String,
    pub policy_blake3: String,
    pub vault_id: VaultId,
    pub approving_owner_keys: usize,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct JoinGenesisPayloadV1 {
    schema: u16,
    purpose: String,
    provider: String,
    endpoint: String,
    region: String,
    force_path_style: bool,
    bucket: String,
    current_head_key: String,
    vault_id: VaultId,
    root_generation: u64,
    root_blake3: String,
    policy_epoch: u64,
    policy_blake3: String,
    recipient_challenge_hex: String,
}

fn is_lower_hex(value: &str, n: usize, require_nonzero: bool) -> bool {
    value.len() == n
        && value.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        && (!require_nonzero || value.bytes().any(|b| b != b'0'))
}

fn approved_keys_sane(keys: &[[u8; 32]], quorum: usize) -> bool {
    (1..=MAX_OWNER_KEYS).contains(&keys.len())
        && (1..=keys.len()).contains(&quorum)
        && keys.iter().all(|key| key.iter().any(|b| *b != 0))
        && keys.iter().copied().collect::<BTreeSet<_>>().len() == keys.len()
}

/// E3a joins ONLY exact genesis and a policy with epoch=1. E3b must check the
/// pinned manifest/index/ETag from remote storage and future versions' history.
/// The root and policy objects here are IN-MEMORY and could be attacker supplied.
pub fn review_offline_join_genesis(
    signed_offer: &DecodedDsseEnvelope<'_>,
    remote_genesis: &S3PackedHeadV2,
    remote_policy: &PublisherPolicyV1,
    approved: &IndependentlyApprovedJoin<'_>,
) -> Result<JoinGenesisReview, JoinGenesisError> {
    if !approved_keys_sane(approved.trusted_owner_keys, approved.owner_quorum)
        || !is_lower_hex(approved.pinned_genesis_root_blake3, 64, false)
        || !is_lower_hex(approved.pinned_genesis_policy_blake3, 64, false)
        || !is_lower_hex(approved.recipient_challenge_hex, 64, true)
    {
        return Err(JoinGenesisError::InvalidExternalApproval);
    }
    if !valid_for_scope(remote_policy, approved.bucket, approved.keyspace) {
        return Err(JoinGenesisError::InvalidPolicy);
    }
    if remote_genesis.generation() != 1 || remote_policy.epoch() != 1 {
        return Err(JoinGenesisError::NotGenesis);
    }
    let root_digest = remote_genesis.digest(approved.keyspace)
        .map_err(|_| JoinGenesisError::WrongRootOrPolicy)?;
    let policy_digest = remote_policy.canonical_digest()
        .map_err(|_| JoinGenesisError::InvalidPolicy)?;
    if root_digest != approved.pinned_genesis_root_blake3
        || policy_digest != approved.pinned_genesis_policy_blake3
    {
        return Err(JoinGenesisError::WrongIndependentPin);
    }
    let (owners, threshold) = remote_policy.trusted_owners();
    if threshold != approved.owner_quorum
        || owners.iter().copied().collect::<BTreeSet<_>>()
            != approved.trusted_owner_keys.iter().copied().collect::<BTreeSet<_>>()
    {
        return Err(JoinGenesisError::WrongOwnerAuthority);
    }
    if signed_offer.payload_type != JOIN_GENESIS_TYPE {
        return Err(JoinGenesisError::InvalidType);
    }
    if signed_offer.payload.is_empty()
        || signed_offer.payload.len() > MAX_JOIN_PAYLOAD_BYTES
        || signed_offer.signatures.is_empty()
        || signed_offer.signatures.len() > MAX_JOIN_SIGNATURES
        || signed_offer.signatures.iter().any(|s| s.sig.len() != 64
            || s.keyid.is_some_and(|v| v.len() > 128))
    {
        return Err(JoinGenesisError::InvalidEnvelope);
    }
    let authenticated = pae(signed_offer.payload_type.as_bytes(), signed_offer.payload);
    let approving_owner_keys = approved.trusted_owner_keys.iter().filter(|key| {
        let verifier = UnparsedPublicKey::new(&ED25519, key);
        signed_offer.signatures.iter().any(|s| {
            verifier.verify(&authenticated, s.sig).is_ok()
        })
    }).count();
    if approving_owner_keys < approved.owner_quorum {
        return Err(JoinGenesisError::MissingOwnerQuorum);
    }
    // Interpret ONLY the bytes whose DSSE PAE signature(s) were verified.
    let offer: JoinGenesisPayloadV1 = serde_json::from_slice(signed_offer.payload)
        .map_err(|_| JoinGenesisError::InvalidSignedPayload)?;
    if offer.schema != 1 || offer.purpose != "review-only-join-genesis" {
        return Err(JoinGenesisError::InvalidSignedPayload);
    }
    if offer.provider != "yandex-object-storage"
        || offer.endpoint != YANDEX_ENDPOINT
        || offer.region != YANDEX_REGION
        || !offer.force_path_style
        || offer.bucket != approved.bucket
        || offer.current_head_key != approved.keyspace.current_head_key()
        || offer.vault_id != approved.keyspace.vault_id()
    {
        return Err(JoinGenesisError::WrongScope);
    }
    if offer.root_generation != remote_genesis.generation()
        || offer.root_blake3 != root_digest
        || offer.policy_epoch != remote_policy.epoch()
        || offer.policy_blake3 != policy_digest
    {
        return Err(JoinGenesisError::WrongRootOrPolicy);
    }
    if offer.recipient_challenge_hex != approved.recipient_challenge_hex {
        return Err(JoinGenesisError::WrongChallenge);
    }
    Ok(JoinGenesisReview {
        root_blake3: root_digest,
        policy_blake3: policy_digest,
        vault_id: approved.keyspace.vault_id(),
        approving_owner_keys,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sync::{DecodedSignature, OperationId};
    use ring::signature::{Ed25519KeyPair, KeyPair};
    use serde_json::{json, Value};

    const CHALLENGE: &str =
        "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

    fn signer(seed: u8) -> Ed25519KeyPair {
        Ed25519KeyPair::from_seed_unchecked(&[seed; 32]).unwrap()
    }
    fn pk(key: &Ed25519KeyPair) -> [u8; 32] {
        key.public_key().as_ref().try_into().unwrap()
    }

    struct Fixture {
        ns: S3Keyspace,
        root: S3PackedHeadV2,
        policy: PublisherPolicyV1,
        root_pin: String,
        policy_pin: String,
        owner: Ed25519KeyPair,
        second: Ed25519KeyPair,
        foreign: Ed25519KeyPair,
        owner_keys: Vec<[u8; 32]>,
    }
    impl Fixture {
        fn new(two_owners: bool) -> Self {
            let ns = S3Keyspace::new("akula/genesis-pairing", VaultId::new()).unwrap();
            let root = S3PackedHeadV2::new(
                &ns, 1, OperationId::new(),
                &blake3::hash(b"e3a-m").to_hex().to_string(),
                OperationId::new(),
                &blake3::hash(b"e3a-i").to_hex().to_string(), None,
            ).unwrap();
            let owner = signer(7);
            let second = signer(8);
            let foreign = signer(42);
            let owner_keys = if two_owners {
                vec![pk(&owner), pk(&second)]
            } else { vec![pk(&owner)] };
            let policy_json = json!({
                "schema": 1,
                "epoch": 1,
                "provider": "yandex-object-storage",
                "endpoint": YANDEX_ENDPOINT,
                "region": YANDEX_REGION,
                "force_path_style": true,
                "bucket": "akula-join-genesis",
                "vault_id": ns.vault_id(),
                "current_head_key": ns.current_head_key(),
                "owner_keys": &owner_keys,
                "owner_quorum": if two_owners { 2 } else { 1 },
                "publisher_keys": [pk(&signer(99))],
                "publisher_quorum": 1,
                "previous_policy_blake3": null,
            });
            let policy = PublisherPolicyV1::parse_for_review(
                &serde_json::to_vec(&policy_json).unwrap(),
            ).unwrap();
            let root_pin = root.digest(&ns).unwrap();
            let policy_pin = policy.canonical_digest().unwrap();
            Self { ns, root, policy, root_pin, policy_pin, owner, second,
                foreign, owner_keys }
        }

        fn approved(&self) -> IndependentlyApprovedJoin<'_> {
            IndependentlyApprovedJoin {
                bucket: "akula-join-genesis",
                keyspace: &self.ns,
                pinned_genesis_root_blake3: &self.root_pin,
                pinned_genesis_policy_blake3: &self.policy_pin,
                trusted_owner_keys: &self.owner_keys,
                owner_quorum: self.owner_keys.len(),
                recipient_challenge_hex: CHALLENGE,
            }
        }
        fn offer(&self) -> Vec<u8> {
            serde_json::to_vec(&JoinGenesisPayloadV1 {
                schema: 1,
                purpose: "review-only-join-genesis".to_string(),
                provider: "yandex-object-storage".to_string(),
                endpoint: YANDEX_ENDPOINT.to_string(),
                region: YANDEX_REGION.to_string(),
                force_path_style: true,
                bucket: "akula-join-genesis".to_string(),
                current_head_key: self.ns.current_head_key(),
                vault_id: self.ns.vault_id(),
                root_generation: 1,
                root_blake3: self.root_pin.clone(),
                policy_epoch: 1,
                policy_blake3: self.policy_pin.clone(),
                recipient_challenge_hex: CHALLENGE.to_string(),
            }).unwrap()
        }
        fn review(&self, bytes: &[u8], keys: &[&Ed25519KeyPair])
            -> Result<JoinGenesisReview, JoinGenesisError>
        {
            self.review_with(bytes, keys, &self.approved(), &self.root, &self.policy)
        }
        fn review_with(&self, bytes: &[u8], keys: &[&Ed25519KeyPair],
            approved: &IndependentlyApprovedJoin<'_>,
            root: &S3PackedHeadV2, policy: &PublisherPolicyV1)
            -> Result<JoinGenesisReview, JoinGenesisError>
        {
            let pae_bytes = pae(JOIN_GENESIS_TYPE.as_bytes(), bytes);
            let raw: Vec<Vec<u8>> = keys.iter()
                .map(|key| key.sign(&pae_bytes).as_ref().to_vec()).collect();
            let signatures: Vec<_> = raw.iter().map(|sig| DecodedSignature {
                sig, keyid: Some("untrusted-owner-label"),
            }).collect();
            review_offline_join_genesis(
                &DecodedDsseEnvelope {
                    payload_type: JOIN_GENESIS_TYPE, payload: bytes, signatures: &signatures,
                }, root, policy, approved,
            )
        }
    }

    #[test]
    fn exact_genesis_and_separate_approved_owner_key_are_required() {
        let f = Fixture::new(false);
        let ok = f.review(&f.offer(), &[&f.owner]).unwrap();
        assert_eq!(ok.root_blake3, f.root_pin);
        assert_eq!(ok.policy_blake3, f.policy_pin);
        assert_eq!(ok.approving_owner_keys, 1);
        assert_eq!(ok.vault_id, f.ns.vault_id());
    }

    #[test]
    fn two_distinct_owner_signatures_are_required_for_quorum_two() {
        let f = Fixture::new(true);
        assert_eq!(f.review(&f.offer(), &[&f.owner, &f.second])
            .unwrap().approving_owner_keys, 2);
        assert_eq!(f.review(&f.offer(), &[&f.owner, &f.owner]),
            Err(JoinGenesisError::MissingOwnerQuorum));
        assert_eq!(f.review(&f.offer(), &[&f.second]),
            Err(JoinGenesisError::MissingOwnerQuorum));
    }

    #[test]
    fn signing_key_from_untrusted_s3_is_not_an_approved_owner() {
        let f = Fixture::new(false);
        assert_eq!(f.review(&f.offer(), &[&f.foreign]),
            Err(JoinGenesisError::MissingOwnerQuorum));
        let mut approval = f.approved();
        let keys = [pk(&f.foreign)];
        approval.trusted_owner_keys = &keys;
        assert_eq!(f.review_with(&f.offer(), &[&f.foreign],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::WrongOwnerAuthority));
    }

    #[test]
    fn independent_root_and_policy_pins_cannot_be_supplied_by_other_vault() {
        let f = Fixture::new(false);
        let mut approval = f.approved();
        let foreign_root_pin = "0".repeat(64);
        approval.pinned_genesis_root_blake3 = &foreign_root_pin;
        assert_eq!(f.review_with(&f.offer(), &[&f.owner],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::WrongIndependentPin));
        let mut approval = f.approved();
        let foreign_policy_pin = "f".repeat(64);
        approval.pinned_genesis_policy_blake3 = &foreign_policy_pin;
        assert_eq!(f.review_with(&f.offer(), &[&f.owner],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::WrongIndependentPin));
    }

    #[test]
    fn changed_bucket_namespace_endpoint_or_vault_is_refused() {
        let f = Fixture::new(false);
        for (field, changed) in [
            ("bucket", json!("foreign-bucket")),
            ("current_head_key", json!("other/vault/refs/current.json")),
            ("endpoint", json!("https://evil.invalid")),
            ("region", json!("wrong-region")),
            ("vault_id", json!(VaultId::new())),
        ] {
            let mut payload: Value = serde_json::from_slice(&f.offer()).unwrap();
            payload[field] = changed;
            let bytes = serde_json::to_vec(&payload).unwrap();
            assert_eq!(f.review(&bytes, &[&f.owner]), Err(JoinGenesisError::WrongScope));
        }
    }

    #[test]
    fn wrong_recipient_challenge_or_missing_freshness_is_refused() {
        let f = Fixture::new(false);
        let mut json: Value = serde_json::from_slice(&f.offer()).unwrap();
        json["recipient_challenge_hex"] = json!("a".repeat(64));
        let bytes = serde_json::to_vec(&json).unwrap();
        assert_eq!(f.review(&bytes, &[&f.owner]), Err(JoinGenesisError::WrongChallenge));
        let mut approval = f.approved();
        let zero_challenge = "0".repeat(64);
        approval.recipient_challenge_hex = &zero_challenge;
        assert_eq!(f.review_with(&f.offer(), &[&f.owner],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::InvalidExternalApproval));
    }

    #[test]
    fn envelope_type_keyid_and_signature_tampering_do_not_bypass_authority() {
        let f = Fixture::new(false);
        let bytes = f.offer();
        let sig_bytes = f.owner.sign(&pae(JOIN_GENESIS_TYPE.as_bytes(), &bytes));
        let signature = [DecodedSignature {
            sig: sig_bytes.as_ref(), keyid: Some("forged-root-owner"),
        }];
        assert_eq!(review_offline_join_genesis(
            &DecodedDsseEnvelope { payload_type: "application/json",
                payload: &bytes, signatures: &signature },
            &f.root, &f.policy, &f.approved(),
        ), Err(JoinGenesisError::InvalidType));
        let corrupted = [DecodedSignature { sig: &[0; 64], keyid: Some("owner") }];
        assert_eq!(review_offline_join_genesis(
            &DecodedDsseEnvelope { payload_type: JOIN_GENESIS_TYPE,
                payload: &bytes, signatures: &corrupted },
            &f.root, &f.policy, &f.approved(),
        ), Err(JoinGenesisError::MissingOwnerQuorum));
        assert_eq!(review_offline_join_genesis(
            &DecodedDsseEnvelope { payload_type: JOIN_GENESIS_TYPE,
                payload: b"{}", signatures: &signature },
            &f.root, &f.policy, &f.approved(),
        ), Err(JoinGenesisError::MissingOwnerQuorum));
    }

    #[test]
    fn signed_unknown_or_duplicate_json_fields_are_rejected() {
        let f = Fixture::new(false);
        let mut value: Value = serde_json::from_slice(&f.offer()).unwrap();
        value["write_authority"] = json!(true);
        let bytes = serde_json::to_vec(&value).unwrap();
        assert_eq!(f.review(&bytes, &[&f.owner]),
            Err(JoinGenesisError::InvalidSignedPayload));
        let original = String::from_utf8(f.offer()).unwrap();
        let duplicate = format!("{},\"schema\":1}}", original.trim_end_matches('}'));
        assert_eq!(f.review(duplicate.as_bytes(), &[&f.owner]),
            Err(JoinGenesisError::InvalidSignedPayload));
    }

    #[test]
    fn invalid_independent_owner_approvals_are_rejected() {
        let f = Fixture::new(false);
        let keys = [pk(&f.owner), pk(&f.owner)];
        let mut approval = f.approved();
        approval.trusted_owner_keys = &keys;
        approval.owner_quorum = 2;
        assert_eq!(f.review_with(&f.offer(), &[&f.owner],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::InvalidExternalApproval));
        let mut approval = f.approved();
        approval.owner_quorum = 0;
        assert_eq!(f.review_with(&f.offer(), &[&f.owner],
            &approval, &f.root, &f.policy),
            Err(JoinGenesisError::InvalidExternalApproval));
    }

    #[test]
    fn never_autoenroll_a_newer_root_or_later_policy_from_remote() {
        let f = Fixture::new(false);
        let newer = S3PackedHeadV2::new(&f.ns, 2, OperationId::new(),
            &blake3::hash(b"m2").to_hex().to_string(),
            OperationId::new(), &blake3::hash(b"i2").to_hex().to_string(),
            Some(f.root_pin.clone())).unwrap();
        assert_eq!(f.review_with(&f.offer(), &[&f.owner], &f.approved(),
            &newer, &f.policy), Err(JoinGenesisError::NotGenesis));
        let mut policy: Value = serde_json::to_value(&f.policy).unwrap();
        policy["epoch"] = json!(2);
        policy["previous_policy_blake3"] = json!(f.policy_pin);
        let newer = PublisherPolicyV1::parse_for_review(
            &serde_json::to_vec(&policy).unwrap()).unwrap();
        assert_eq!(f.review_with(&f.offer(), &[&f.owner], &f.approved(),
            &f.root, &newer), Err(JoinGenesisError::NotGenesis));
    }

    #[test]
    fn valid_pins_are_not_enough_without_a_signature() {
        let f = Fixture::new(false);
        assert_eq!(f.review(&f.offer(), &[]), Err(JoinGenesisError::InvalidEnvelope));
        let mut json: Value = serde_json::from_slice(&f.offer()).unwrap();
        json["root_blake3"] = json!("f".repeat(64));
        let bytes = serde_json::to_vec(&json).unwrap();
        assert_eq!(f.review(&bytes, &[&f.owner]),
            Err(JoinGenesisError::WrongRootOrPolicy));
    }

    #[test]
    fn payload_size_limit_rejects_even_a_synthetically_signed_large_offer() {
        let f = Fixture::new(false);
        let bytes = vec![b'x'; MAX_JOIN_PAYLOAD_BYTES + 1];
        assert_eq!(f.review(&bytes, &[&f.owner]), Err(JoinGenesisError::InvalidEnvelope));
    }
}
